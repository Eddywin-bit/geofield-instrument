import { defineConfig } from "@lovable.dev/vite-tanstack-config";

// Set CAPACITOR_BUILD=1 only in the Android CI build. It switches TanStack Start
// into SPA mode so a static shell is prerendered for packaging inside the APK.
// The Lovable web deployment does NOT set this, and keeps full SSR.
const capacitorBuild = process.env.CAPACITOR_BUILD === "1";

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
    ...(capacitorBuild ? { spa: { enabled: true } } : {}),
  },
});
